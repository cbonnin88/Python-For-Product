"""# **Phase 3: A/B Testing & Statistical Rigor**"""

orders_df = (
    df_product_clean
    .group_by(['Customer ID','Invoice'])
    .agg(pl.col('Revenue').sum().alias('OrderValue'))
    .with_columns(
        # Assign Control (A) or Treatment (B) deterministically based on odd/even Customer ID
        pl.when(pl.col('Customer ID').cast(pl.Int64) % 2 == 0)
        .then(pl.lit('Control')) # Added .then() for the true condition
        .otherwise(pl.lit('Treatment'))
        .alias('ExperimentGroup')

    )
)

np.random.seed(42)
orders_pd = orders_df.to_pandas() # Changed order_df to orders_df to match the DataFrame name
treatment_mask = order_pd['ExperimentGroup'] == 'Treatment'
order_pd.loc[treatment_mask, 'OrderValue']*= np.random.normal(1.05,0.1,size=treatment_mask.sum())

"""# **1. Sample Ratio Mismatch (SRM) Test**"""

# Before checking revenue, we must run a Chi-Square ($\chi^2$) test to verify traffic was routed evenly without systemic tracking bugs.

group_counts = orders_pd['ExperimentGroup'].value_counts()
observed = [group_counts['Control'], group_counts['Treatment']]
expected = [len(orders_pd) / 2, len(orders_pd) / 2] # Corrected: len(order_pd) is divided by 2, not the DataFrame itself.

chi2_stat, p_val_srm = stats.chisquare(f_obs=observed,f_exp=expected)

print('--- Sample Ration Mismatch (SRM) Check ---')
print(f'Observed: Control={observed[0]:,}, Treatment={observed[1]:,}')
print(f'Chi-Square Stat: {chi2_stat:.4f} | p-value: {p_val_srm:.4f}')
if p_val_srm < 0.01:
  print('WARNING: Statistically significant SRM detected! Do not trust test metrics.')
else:
  print('SUCCESS: Traffic split is balanced. Proceed to hypothesis testing.')

"""# **2. Hypothesis Testing ($t$-test & Mann-Whitney U)**"""

# We test whether the difference in means is statistically significant.

control_rev = orders_pd[orders_pd['ExperimentGroup']== 'Control']['OrderValue']
treatment_rev = orders_pd[order_pd['ExperimentGroup']== 'Treatment']['OrderValue']

# Two-Sample t-test
t_stat, p_val_t = stats.ttest_ind(treatment_rev,control_rev,equal_var=False)

# Non-parametric Mann-Whitney U test
u_stat, p_val_u  = stats.mannwhitneyu(treatment_rev, control_rev, alternative='two-sided')

print("\n--- Hypothesis Testing Results ---")
print(f"Control Mean: £{control_rev.mean():.2f} | Treatment Mean: £{treatment_rev.mean():.2f}")
print(f"Absolute Lift: £{treatment_rev.mean() - control_rev.mean():.2f} ({(treatment_rev.mean()/control_rev.mean() - 1)*100:.2f}%)")
print(f"Welch's t-test p-value: {p_val_t:.5f}")
print(f"Mann-Whitney U p-value: {p_val_u:.5f}")

"""# **3. Variance Reduction: CUPED**

- CUPED (Controlled Experiments Using Pre-Experiment Data) uses a user's pre-experiment spend ($X$) as a covariate to shrink the variance of post-experiment spend ($Y$), allowing you to detect smaller lifts with greater statistical power.

- The adjusted metric is calculated as:


```
Ycuped = Y - 0(X-X)
```



```
where 0 = Cov(X,Y)/Var(x)
```


"""

# # Simulate pre-experiment baseline spend (X) correlated with experiment spend (Y)
orders_pd['Pre_Experiment_Spend'] = orders_pd['OrderValue'] * np.random.normal(0.8,0.2, size=len(orders_pd)) + np.random.normal(10,5,size=len(orders_pd))

X = orders_pd['Pre_Experiment_Spend']
Y = orders_pd['OrderValue']
X_mean = X.mean()

# Calculate Theta
covariance = np.cov(X,Y)[0,1]
variance_X = np.var(X,ddof=1)
theta = covariance / variance_X

# Apply CUPED adjustment
orders_pd['OrderValue_CUPED'] = Y - theta * (X-X_mean)

# Compare standard Errors before and after CUPED
se_original = orders_pd.groupby('ExperimentGroup')['OrderValue'].sem()
se_cuped = orders_pd.groupby('ExperimentGroup')['OrderValue_CUPED'].sem()

print("\n--- CUPED Variance Reduction ---")
print(f"Theta: {theta:.4f}")
print(f"Original Standard Error: Control={se_original['Control']:.2f}, Treatment={se_original['Treatment']:.2f}")
print(f"CUPED Standard Error:    Control={se_cuped['Control']:.2f}, Treatment={se_cuped['Treatment']:.2f}")
print(f"Variance Reduction: {(1 - (se_cuped['Control']/se_original['Control'])**2)*100:.1f}%")

"""# **Phase 4: User Segmentation & Predictive Analytics**

1. Behavioral Clustering (RFM + K-Means)
"""

# We calculate Recency, Frequency, and Monetary (RFM) metrics per user and apply K-Means clustering to group them into behavioral archetypes.

max_date = df_product_clean['OrderDate'].max()

rfm_df = (
    df_product_clean
    .group_by('Customer ID')
    .agg(
        ((max_date - pl.col('OrderDate').max()).dt.total_days()).alias('Recency'),
        pl.col('Invoice').n_unique().alias('Frequency'),
        pl.col('Revenue').sum().alias('Monetary')
    )
    .filter(pl.col('Monetary') > 0)
)

# Prepare data for Scikit-Learn
rfm_pd = rfm_df.to_pandas()
X_rfm = rfm_pd[['Recency','Frequency','Monetary']]

# Log-transform and Scale features to handle extreme retail outliers
X_scaled = StandardScaler().fit_transform(np.log1p(X_rfm))

# Train K-Means
kmeans = KMeans(n_clusters=4,random_state=42,n_init=10)
rfm_pd['Cluster'] = kmeans.fit_predict(X_scaled).astype(str)

# Map clusters to descriptive Product Archestypes based on means
cluster_summary = rfm_pd.groupby('Cluster')[['Recency','Frequency','Monetary']].mean()
print('Cluster Profiles:')
