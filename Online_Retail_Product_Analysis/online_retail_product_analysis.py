"""2. Churn Prediction (Random Forest)

- Let's predict which customers will churn in the second half of the year based on their behavior in the first 90 days.
"""

# Split data into Observation Window (First 90 days) and Performance Window (Next 180 days)
start_date = df_product_clean['OrderDate'].min()
obs_end = start_date + pd.Timedelta(days=90)

obs_data = df_product_clean.filter(pl.col('OrderDate')<= obs_end)
perf_data = df_product_clean.filter(pl.col('OrderDate') > obs_end)

# Build feature from Observation Window
features = (
    obs_data
    .group_by('Customer ID')
    .agg(
        pl.col('Invoice').n_unique().alias('Obs_Orders'),
        pl.col('Revenue').sum().alias('Obs_Revenue'),
        pl.col('Quantity').sum().alias('Obs_Units'),
        ((obs_end - pl.col('OrderDate').max()).dt.total_days()).alias('Obs_Recency')
    )
)

# Identify who returned in the Performance Window (0= Churned, 1= Retained)
active_future = perf_data.select('Customer ID').unique().with_columns(pl.lit(0).alias('Churned'))
churn_dataset = (
    features
    .join(active_future, on='Customer ID',how='left')
    .with_columns(pl.col('Churned').fill_null(1)) # If null in future, they churned (=1)
).to_pandas()

# Train/Test Split
X = churn_dataset[['Obs_Orders','Obs_Revenue','Obs_Units','Obs_Recency']]
y = churn_dataset['Churned']
X_train,X_test,y_train,y_test = train_test_split(X,y,test_size=0.25,random_state=42)

# Train Classifier
clf = RandomForestClassifier(n_estimators=100,max_depth=5,random_state=42)
clf.fit(X_train,y_train)
preds = clf.predict_proba(X_test)[:, 1]

print("--- Churn Prediction Model Performance ---")
print(f"ROC-AUC Score: {roc_auc_score(y_test, preds):.3f}")
print("Feature Importances:", dict(zip(X.columns, clf.feature_importances_.round(3))))

