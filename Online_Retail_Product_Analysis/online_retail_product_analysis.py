"""# **Phase 5: Automating Repetitive Data Workflows**

Automated Rolling $z$-Score Anomaly Detection

- This script calculates daily revenue, evaluates a 14-day rolling window to compute a *z-score*, and automatically flags anomaly days where `z > 2.5`



```
z= xi - rolling / Orolling
```


"""

# Aggregate Daily Revenue
daily_rev = (
    df_product_clean
    .group_by('OrderDate')
    .agg(pl.col('Revenue').sum().alias('Daily_Revenue'))
    .sort('OrderDate')
).to_pandas()

# Calculate 14-day rolling mean and standard Deviation
daily_rev['Rolling_Mean'] = daily_rev['Daily_Revenue'].rolling(window=14,min_periods=7).mean()
daily_rev['Rolling_Std'] = daily_rev['Daily_Revenue'].rolling(window=14,min_periods=7).std()

#. Calcuate z-score and flag anomalies
daily_rev['Z_Score'] = (daily_rev['Daily_Revenue'] - daily_rev['Rolling_Mean']) / daily_rev['Rolling_Std']
daily_rev['Is_Anomaly'] = daily_rev['Z_Score'].abs() > 2.5

fig_std = px.line(
    daily_rev,
    x='OrderDate',
    y='Daily_Revenue',
    title='Automated Anomaly Detection (Rolling Z-Socre > 2.5)',
    labels={'Daily_Revenue': 'Daily Revenue','OrderDate':'Order Date'}
)
anomalies = daily_rev[daily_rev['Is_Anomaly']]
fig_std.add_trace(go.Scatter(
    x=anomalies['OrderDate'],
    y=anomalies['Daily_Revenue'],
    mode='markers',
    name='Anomalies',
    marker=dict(color='red',size=10,symbol='x')
))
fig_std.show()

print(f"Detected {len(anomalies)} anomaly days in the transaction logs.")