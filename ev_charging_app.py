@st.cache_data
def generate_mock_data(n_users=3000):
  """
    Generates mock data for an EV Charging App in Western Europe.
    The variant group will have a slightly better performance to simulate a successful A/B test.
  """
  np.random.seed(42)

  countries = np.random.choice(['France','Netherlands','United Kingdom','Norway'],n_users,p=[0.3,0.4,0.2,0.1])
  personas = np.random.choice(['Casual','Commuter','Fleet Driver'],n_users,p=[0.5,0.4,0.1])
  groups = np.random.choice(['Control','Variant'],n_users,p=[0.5,0.5])

  df_ev = pd.DataFrame({
      'user_id': range(1,n_users + 1),
      'country': countries,
      'persona': personas,
      'group': groups
  })

  # Generate metrics with a slight uplift for the Variant group
  # Metric 1: Charging sessions per week (Continuous data)
  base_sessions = np.random.normal(loc=2.5,scale=1.0,size=n_users)
  variant_uplift_sessions = np.where(df_ev['group'] == 'Variant',0.4,0.0)

  # Add a country specific bias (e.g., Netherlands charges more frequently)
  country_bias = np.where(df_ev['country']=='Variant',0.5,0.0)

  df_ev['sessions_per_week'] = np.maximum(0,np.round(base_sessions + variant_uplift_sessions + country_bias, 1))

  # Metric 2: Premium Subscription Conversion (Binary data 0 or 1)
  # Control conversion rate ~ 12%, Variant ~ 15%
  base_prob = 0.12
  variant_prob = 0.15
  probabilities = np.where(df_ev['group']=='Control',base_prob,variant_prob)
  df_ev['converted_to_premium'] = np.random.binomial(1,probabilities)

  return df_ev

# Statistical Functions
def calculate_significance_means(control_data, variant_data):
  'Performas a T-test for continuous variables (e.g. sessiosn per week)'
  t_stat, p_val = stats.ttest_ind(control_data,variant_data,equal_var=False)
  return t_stat,p_val

def calculate_significance_proportions(control_conv,control_total,variant_conv,variant_total):
  'Performs a Z-test for binary proportions (e.g., conversion rates).'
  counts =  np.array([variant_conv, control_conv])
  nobs = np.array([variant_total, control_total])
  z_stat, p_val = proportions_ztest(counts,nobs)
  return z_stat,p_val

def calculate_mde(baseline_rate,sample_size_per_group,power=0.8,alpha=0.05):
  'Calculate Minimum Detectable Effect using statsmodels'
  analysis = NormalIndPower()
  effect_size = analysis.solve_power(
      effect_size=None,
      power=power,
      alpha=alpha,
      nobs1=sample_size_per_group,
      ratio=1.0 # 50/50 split
  )

  # Convert Cohen's h back to p2 (approximation for proportion MDE)
  p1 = baseline_rate
  p2_asin = math.asin(math.sqrt(p1)) + (effect_size / 2)
  p2 = math.sin(p2_asin) ** 2

  absolute_mde = (p2-p1)
  relative_mde = absolute_mde / p1
  return absolute_mde, relative_mde


