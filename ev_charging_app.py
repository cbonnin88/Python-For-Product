  st.title('🧪 A/B Test Analyzer')

  st.write('Analyze the results of our Smart Route experiment to see if it significantly impacted user behavior.')

  st.subheader('1. Premium Subscription Conversion (Z-Test)')
  # Calculate totals and conversions
  control_mask = df_ev['group'] == 'Control'
  variant_mask = df_ev['group'] == 'Variant'

  ctrl_total = control_mask.sum()
  var_total = variant_mask.sum()
  ctrl_conv = df_ev[control_mask]['converted_to_premium'].sum()
  var_conv = df_ev[variant_mask]['converted_to_premium'].sum()

  ctrl_rate = ctrl_conv / ctrl_total
  var_rate = var_conv / var_total

  col1,col2,col3 = st.columns(3)
  col1.metric('Control Conversion',f'{ctrl_rate:.2%}')
  col2.metric('Variant Conversion',f'{var_rate:.2%}',f'{(var_rate - ctrl_rate):.2%} absolute diff')

  # Statistical Test
  z_stat, p_val_z = calculate_significance_proportions(ctrl_conv,ctrl_total,var_conv,var_total)
  is_sig_z = p_val_z < 0.05

  col3.metric('Statistically Significant ?','Yes ✅' if is_sig_z else 'No ❌',f'p-value: {p_val_z:.4f}')

  st.subheader('2. Weekly Charging Sessions (T-Test)')
  ctrl_mean = df_ev[control_mask]['sessions_per_week'].mean()
  var_mean = df_ev[variant_mask]['sessions_per_week'].mean()

  col1,col2,col3 = st.columns(3)
  col1.metric('Control Avg Sessions',f'{ctrl_mean:.2f}')
  col2.metric('Variant Avg Sessions',f'{var_mean:.2f}',f'{(var_mean - ctrl_mean):.2f} diff')

  t_stat, p_val_t = calculate_significance_means(df_ev[control_mask]['sessions_per_week'],df_ev[variant_mask]['sessions_per_week'])
  is_sig_t = p_val_t < 0.05

  col3.metric('Statistically Significant?','Yes ✅' if is_sig_t else 'No ❌',f'p-value:{p_val_t:.4f}')

